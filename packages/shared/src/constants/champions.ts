/**
 * 通过英雄 ID 获取显示名称：称号(英雄名)
 * 例如：黑暗之女(安妮)
 */
export function getChampionDisplayName(id: number): string {
  const cnName = CHAMPION_CN_NAME_MAP[id];
  const title = CHAMPION_TITLE_MAP[id];
  if (title && cnName) return `${title} - ${cnName}`;
  if (cnName) return cnName;
  return CHAMPION_ID_MAP[id] ?? '未知英雄';
}
